#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { getAvailableBanks } from '../../src/config/bank-registry.js';

const projectRoot = process.cwd();
const inputDir = path.join(projectRoot, 'src', 'config', 'flashcard-banks');
const staleOutputDir = path.join(projectRoot, 'src', 'pages', 'practice-sub', 'flashcard-banks');
const outputFile = path.join(projectRoot, 'src', 'pages', 'practice-sub', 'bank-data-table.js');

function splitBase64(value, size = 120) {
  const chunks = [];
  for (let index = 0; index < value.length; index += size) {
    chunks.push(value.slice(index, index + size));
  }
  return chunks;
}

function bankIdFromFile(fileName) {
  return fileName.replace(/\.json$/, '');
}

function buildBankEntrySource(bankId, compressedBase64) {
  const chunks = splitBase64(compressedBase64);
  return [
    `  '${bankId}': [`,
    chunks.map((chunk) => `  '${chunk}'`).join(',\n'),
    "  ].join('')"
  ].join('\n');
}

function buildTableSource(entries) {
  return [
    '// Generated by scripts/build/generate-compressed-bank-modules.mjs. Do not edit manually.',
    '',
    'export const COMPRESSED_BANK_DATA_BY_ID = Object.freeze({',
    entries.map(({ bankId, compressedBase64 }) => buildBankEntrySource(bankId, compressedBase64)).join(',\n'),
    '});',
    ''
  ].join('\n');
}

function run() {
  if (!fs.existsSync(inputDir)) {
    throw new Error(`[compressed-bank-modules] input dir not found: ${inputDir}`);
  }

  fs.rmSync(staleOutputDir, { recursive: true, force: true });
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });

  const publishedBankIds = new Set(getAvailableBanks().map((bank) => bank.id));
  const files = fs
    .readdirSync(inputDir)
    .filter((fileName) => fileName.endsWith('.json'))
    .filter((fileName) => publishedBankIds.has(bankIdFromFile(fileName)))
    .sort();
  const generatedBankIds = new Set(files.map(bankIdFromFile));
  const missingBankIds = Array.from(publishedBankIds).filter((bankId) => !generatedBankIds.has(bankId));
  if (missingBankIds.length > 0) {
    throw new Error(`[compressed-bank-modules] missing source JSON for published banks: ${missingBankIds.join(', ')}`);
  }

  let rawBytes = 0;
  let compressedBytes = 0;
  const entries = [];

  for (const fileName of files) {
    const bankId = bankIdFromFile(fileName);
    const raw = fs.readFileSync(path.join(inputDir, fileName));
    const compressed = zlib.deflateSync(raw, { level: 9 });
    const compressedBase64 = compressed.toString('base64');
    entries.push({ bankId, compressedBase64 });
    rawBytes += raw.length;
    compressedBytes += compressedBase64.length;
  }

  fs.writeFileSync(outputFile, buildTableSource(entries), 'utf8');

  console.log(
    `[compressed-bank-modules] generated ${files.length} banks: raw=${rawBytes} bytes compressedBase64=${compressedBytes} bytes`
  );
}

run();
